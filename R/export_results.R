map <- c(primary = "cinema_20261112", sensitivity = "sensitivity_20261112", subgroups = "subgroups_20261113", meta_regression = "nmr_20261113")
for (group in names(map)) {
  out <- file.path("results/tables", group); dir.create(out, recursive = TRUE, showWarnings = FALSE)
  files <- list.files(file.path("work", map[group]), pattern = "\\.csv$", full.names = TRUE)
  stopifnot(all(file.copy(files, out, overwrite = TRUE)))
}
plots <- list(sensitivity = c("effects.csv", "rankings.csv", "components.csv", "scenarios.csv", "risk_input.csv"),
              subgroups = c("summary.csv", "effects.csv", "interactions.csv", "adult_restrictions.csv"),
              meta_regression = c("summary.csv", "slopes.csv", "predictions.csv", "bubble_points.csv", "curve_values.csv"))
for (group in names(plots)) {
  target <- file.path("results/plot_data", group); dir.create(target, recursive = TRUE, showWarnings = FALSE)
  src <- file.path("work", map[group], plots[[group]])
  src <- src[file.exists(src)]
  stopifnot(all(file.copy(src, target, overwrite = TRUE)))
}
dir.create("results/model_objects", showWarnings = FALSE)
for (group in names(map)) {
  src <- list.files(file.path("work", map[group]), pattern = "\\.rds$", full.names = TRUE)
  if (length(src)) stopifnot(all(file.copy(src, file.path("results/model_objects", paste0(group, "_", basename(src))), overwrite = TRUE)))
  previews <- list.files(file.path("work", map[group]), pattern = "\\.png$", full.names = TRUE)
  if (length(previews)) {
    target <- file.path("results/previews", group); dir.create(target, recursive = TRUE, showWarnings = FALSE)
    stopifnot(all(file.copy(previews, target, overwrite = TRUE)))
  }
}
